interface CoffeeI18nContextValue {
  locale: CoffeeLocale;
  t: (key: CoffeeTranslationKey) => string;
}

const CoffeeI18nContext = createContext<CoffeeI18nContextValue | null>(null);

export function CoffeeI18nProvider({
  locale,
  children,
}: {
  locale: CoffeeLocale;
  children: ReactNode;
}) {
  const t = useCallback(
    (key: CoffeeTranslationKey) => (locale === 'en' ? en[key] : ru[key]),
    [locale],
  );
  const value = useMemo(() => ({ locale, t }), [locale, t]);
  return (
    <CoffeeI18nContext.Provider value={value}>{children}</CoffeeI18nContext.Provider>
  );
}

export function useCoffeeTranslation(): CoffeeI18nContextValue {
  const context = useContext(CoffeeI18nContext);
  if (!context) {
    throw new Error('Coffee UI must be rendered inside CoffeeI18nProvider');
  }
  return context;
}
